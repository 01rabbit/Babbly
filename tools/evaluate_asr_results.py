#!/usr/bin/env python3
import argparse
import json
from pathlib import Path

from babbly.nlu.japanese import IntentResolver, normalize_japanese
from babbly.nlu.vocabulary import build_aliases


def load_json(path):
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def evaluate(corpus, results):
    aliases = build_aliases("core", "kali", "azazel")
    resolver = IntentResolver(aliases)
    by_id = {item["id"]: item for item in results}

    total = 0
    transcript_exact = 0
    intent_correct = 0
    false_execution = 0
    rows = []

    for expected in corpus:
        result = by_id.get(expected["id"])
        if result is None:
            rows.append({"id": expected["id"], "status": "missing"})
            continue

        total += 1
        expected_text = normalize_japanese(expected["utterance"], aliases)
        actual_text = normalize_japanese(result.get("recognized_text", ""), aliases)
        exact = expected_text == actual_text
        transcript_exact += int(exact)

        if expected["expected_intent"] == "wake":
            actual_intent = "wake" if expected_text in actual_text else "unknown"
        else:
            actual_intent = resolver.resolve(result.get("recognized_text", "")).name

        intent_ok = actual_intent == expected["expected_intent"]
        intent_correct += int(intent_ok)

        expected_nonexec = expected["expected_intent"] in {"unknown", "wake"}
        actual_exec = actual_intent not in {"unknown", "wake"}
        false_exec = expected_nonexec and actual_exec
        false_execution += int(false_exec)

        rows.append(
            {
                "id": expected["id"],
                "expected": expected["utterance"],
                "recognized": result.get("recognized_text", ""),
                "expected_intent": expected["expected_intent"],
                "actual_intent": actual_intent,
                "transcript_exact": exact,
                "intent_correct": intent_ok,
                "false_execution": false_exec,
                "latency_ms": result.get("latency_ms"),
            }
        )

    denominator = max(total, 1)
    latencies = [row["latency_ms"] for row in rows if isinstance(row.get("latency_ms"), (int, float))]
    summary = {
        "evaluated": total,
        "transcript_exact_rate": transcript_exact / denominator,
        "intent_accuracy": intent_correct / denominator,
        "false_execution_rate": false_execution / denominator,
        "mean_latency_ms": (sum(latencies) / len(latencies)) if latencies else None,
    }
    return summary, rows


def main():
    parser = argparse.ArgumentParser(description="Evaluate Babbly offline ASR results")
    parser.add_argument("results", help="JSON results generated by an ASR backend")
    parser.add_argument(
        "--corpus",
        default="benchmarks/ja_command_corpus.json",
        help="Expected utterance corpus JSON",
    )
    parser.add_argument("--json", action="store_true", help="Print machine-readable JSON")
    args = parser.parse_args()

    summary, rows = evaluate(load_json(args.corpus), load_json(args.results))
    if args.json:
        print(json.dumps({"summary": summary, "rows": rows}, ensure_ascii=False, indent=2))
        return

    print(f"evaluated: {summary['evaluated']}")
    print(f"transcript exact rate: {summary['transcript_exact_rate']:.3f}")
    print(f"intent accuracy: {summary['intent_accuracy']:.3f}")
    print(f"false execution rate: {summary['false_execution_rate']:.3f}")
    if summary["mean_latency_ms"] is not None:
        print(f"mean latency ms: {summary['mean_latency_ms']:.1f}")
    for row in rows:
        if row.get("status") == "missing" or not row.get("intent_correct", True):
            print(json.dumps(row, ensure_ascii=False))


if __name__ == "__main__":
    main()
