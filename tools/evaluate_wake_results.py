#!/usr/bin/env python3
import argparse
import json
from pathlib import Path
from statistics import mean


def load_json(path):
    with open(path, "r", encoding="utf-8") as handle:
        data = json.load(handle)
    if not isinstance(data, list):
        raise ValueError(f"{path} must contain a JSON array")
    return data


def _strict_bool(value, field, item_id):
    if type(value) is not bool:
        raise ValueError(f"{item_id}: {field} must be a JSON boolean")
    return value


def _percentile(values, percentile):
    if not values:
        return None
    ordered = sorted(float(value) for value in values)
    if len(ordered) == 1:
        return ordered[0]
    position = (len(ordered) - 1) * percentile
    lower = int(position)
    upper = min(lower + 1, len(ordered) - 1)
    fraction = position - lower
    return ordered[lower] + (ordered[upper] - ordered[lower]) * fraction


def evaluate(corpus, results):
    expected_by_id = {}
    for item in corpus:
        item_id = str(item.get("id") or "").strip()
        if not item_id:
            raise ValueError("corpus item is missing id")
        if item_id in expected_by_id:
            raise ValueError(f"duplicate corpus id: {item_id}")
        _strict_bool(item.get("expected_trigger"), "expected_trigger", item_id)
        expected_by_id[item_id] = item

    result_by_id = {}
    for item in results:
        item_id = str(item.get("id") or "").strip()
        if not item_id:
            raise ValueError("result item is missing id")
        if item_id in result_by_id:
            raise ValueError(f"duplicate result id: {item_id}")
        _strict_bool(item.get("actual_trigger"), "actual_trigger", item_id)
        result_by_id[item_id] = item

    tp = tn = fp = fn = 0
    rows = []
    true_positive_latencies = []

    for item_id, expected in expected_by_id.items():
        result = result_by_id.get(item_id)
        if result is None:
            rows.append({"id": item_id, "status": "missing"})
            continue

        expected_trigger = expected["expected_trigger"]
        actual_trigger = result["actual_trigger"]
        if expected_trigger and actual_trigger:
            tp += 1
            latency = result.get("latency_ms")
            if isinstance(latency, (int, float)) and not isinstance(latency, bool):
                true_positive_latencies.append(float(latency))
        elif not expected_trigger and not actual_trigger:
            tn += 1
        elif not expected_trigger and actual_trigger:
            fp += 1
        else:
            fn += 1

        rows.append(
            {
                "id": item_id,
                "expected_trigger": expected_trigger,
                "actual_trigger": actual_trigger,
                "correct": expected_trigger == actual_trigger,
                "latency_ms": result.get("latency_ms"),
                "class": expected.get("class"),
            }
        )

    positive = tp + fn
    negative = tn + fp
    evaluated = positive + negative
    summary = {
        "corpus_items": len(expected_by_id),
        "evaluated": evaluated,
        "missing": len(expected_by_id) - evaluated,
        "true_positive": tp,
        "true_negative": tn,
        "false_positive": fp,
        "false_negative": fn,
        "accuracy": (tp + tn) / evaluated if evaluated else None,
        "false_accept_rate": fp / negative if negative else None,
        "false_reject_rate": fn / positive if positive else None,
        "mean_true_positive_latency_ms": mean(true_positive_latencies) if true_positive_latencies else None,
        "p95_true_positive_latency_ms": _percentile(true_positive_latencies, 0.95),
    }
    return summary, rows


def main():
    parser = argparse.ArgumentParser(description="Evaluate Babbly wake-word/KWS results")
    parser.add_argument("results", help="JSON results generated by a wake backend")
    parser.add_argument(
        "--corpus",
        default="benchmarks/wake_corpus.json",
        help="Expected wake-word corpus JSON",
    )
    parser.add_argument("--json", action="store_true", help="Print machine-readable JSON")
    args = parser.parse_args()

    summary, rows = evaluate(load_json(args.corpus), load_json(args.results))
    if args.json:
        print(json.dumps({"summary": summary, "rows": rows}, ensure_ascii=False, indent=2))
        return

    print(f"evaluated: {summary['evaluated']} / {summary['corpus_items']}")
    print(f"missing: {summary['missing']}")
    if summary["accuracy"] is not None:
        print(f"accuracy: {summary['accuracy']:.3f}")
    if summary["false_accept_rate"] is not None:
        print(f"false accept rate: {summary['false_accept_rate']:.3f}")
    if summary["false_reject_rate"] is not None:
        print(f"false reject rate: {summary['false_reject_rate']:.3f}")
    if summary["mean_true_positive_latency_ms"] is not None:
        print(f"mean true-positive latency ms: {summary['mean_true_positive_latency_ms']:.1f}")
        print(f"p95 true-positive latency ms: {summary['p95_true_positive_latency_ms']:.1f}")

    for row in rows:
        if row.get("status") == "missing" or not row.get("correct", True):
            print(json.dumps(row, ensure_ascii=False))


if __name__ == "__main__":
    main()
